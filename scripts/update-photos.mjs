// Turns the original photos in src/photo/<gallery>/ into fast web copies in
// public/photos/<gallery>/ and writes shared/photos.js for the site.
//
//   npm run photos
//
// - Each folder in src/photo is one gallery (live, studio, events, weddings, ...).
//   Folders starting with "_" (like _not-on-site) are ignored.
// - Newest photos (by file date) are shown first.
// - Photos that contain GPS location data are skipped, so locations never go online.
// - Needs macOS (uses the built-in `sips` and `mdls` tools). Originals are never changed.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src/photo");
const OUT = path.join(ROOT, "public/photos");
const EXT = /\.(jpe?g|png|heic|webp|tiff?)$/i;

const slug = (name) => name.replace(EXT, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const sips = (...args) => execFileSync("sips", args, { encoding: "utf8" });
const dims = (file) => {
  const out = sips("-g", "pixelWidth", "-g", "pixelHeight", file);
  const w = Number(/pixelWidth: (\d+)/.exec(out)?.[1]);
  const h = Number(/pixelHeight: (\d+)/.exec(out)?.[1]);
  return { w, h };
};
const hasGps = (file) => {
  try {
    return execFileSync("mdls", ["-raw", "-name", "kMDItemLatitude", file], { encoding: "utf8" }).trim() !== "(null)";
  } catch {
    return false;
  }
};
const fresh = (out, src) => fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs;

const groups = fs.readdirSync(SRC, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && !d.name.startsWith("."))
  .map((d) => d.name)
  .sort();

const manifest = {};
let made = 0;
let skipped = 0;

for (const group of groups) {
  const dir = path.join(SRC, group);
  const outDir = path.join(OUT, group);
  fs.mkdirSync(path.join(outDir, "sm"), { recursive: true });

  const files = fs.readdirSync(dir)
    .filter((f) => EXT.test(f) && !f.startsWith("."))
    .map((f) => ({ f, full: path.join(dir, f), mtime: fs.statSync(path.join(dir, f)).mtimeMs }))
    .sort((a, b) => b.mtime - a.mtime);

  const keep = new Set();
  manifest[group] = [];
  for (const { f, full } of files) {
    if (hasGps(full)) {
      console.warn(`  ! skipped ${group}/${f} — it contains GPS location data`);
      skipped += 1;
      continue;
    }
    const name = `${slug(f)}.jpg`;
    const big = path.join(outDir, name);
    const small = path.join(outDir, "sm", name);
    if (!fresh(big, full)) {
      sips("-s", "format", "jpeg", "-Z", "1800", "-s", "formatOptions", "72", full, "--out", big);
      made += 1;
    }
    if (!fresh(small, full)) sips("-s", "format", "jpeg", "-Z", "760", "-s", "formatOptions", "68", full, "--out", small);
    const { w, h } = dims(small);
    keep.add(name);
    manifest[group].push({ src: `/photos/${group}/${name}`, sm: `/photos/${group}/sm/${name}`, wide: w > h });
  }

  // remove web copies whose original was removed from the folder
  for (const sub of [outDir, path.join(outDir, "sm")]) {
    for (const f of fs.readdirSync(sub)) {
      if (f.endsWith(".jpg") && !keep.has(f)) fs.rmSync(path.join(sub, f));
    }
  }
  console.log(`${group}: ${manifest[group].length} photos`);
}

// remove web galleries whose folder no longer exists
for (const d of fs.readdirSync(OUT, { withFileTypes: true })) {
  if (d.isDirectory() && !groups.includes(d.name)) fs.rmSync(path.join(OUT, d.name), { recursive: true });
}

const js = `// Generated by scripts/update-photos.mjs — run \`npm run photos\` after adding photos to src/photo/<gallery>/.
// Do not edit by hand.
export const PHOTOS = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, "shared/photos.js"), js);
console.log(`Done. ${made} new web copies${skipped ? `, ${skipped} skipped` : ""}.`);
